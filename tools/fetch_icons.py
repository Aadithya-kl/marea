here = os.path.dirname(os.path.abspath(__file__))
svg_dir = os.path.join(here, "..", "src", "Marea.App", "Assets", "Icons")
os.makedirs(svg_dir, exist_ok=True)
out = ['<!-- Generated by tools/fetch_icons.py from Fluent UI System Icons (MIT, Microsoft). Do not edit. -->',
       '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
       '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">']
missing = []
for key, (folder, stem, variant) in ICONS.items():
    data = None
    for size in (24, 20):
        name = f"ic_fluent_{stem}_{size}_{variant}.svg"
        url = f"{BASE}/{urllib.parse.quote(folder)}/SVG/{name}"
        try:
            with urllib.request.urlopen(url, timeout=30) as r:
                svg = r.read().decode("utf-8")
            open(os.path.join(svg_dir, name), "w", encoding="utf-8").write(svg)
            paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
            evenodd = 'fill-rule="evenodd"' in svg
            box = re.search(r'viewBox="0 0 (\d+) (\d+)"', svg)
            data = ("F0 " if evenodd else "F1 ") + " ".join(paths)
            break
        except OSError:
            continue
    if data is None:
        missing.append(key)
        continue
    out.append(f'    <Geometry x:Key="Icon.{key}">{data}</Geometry>')
out.append("</ResourceDictionary>")
xaml = os.path.join(here, "..", "src", "Marea.App", "Icons.xaml")
open(xaml, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(ICONS) - len(missing), "icons;", "missing:", missing)
sys.exit(1 if missing else 0)
